// Writes docs/reference/commands.md from the command registry and each command's own usage and options, and
// docs/reference/skill-catalog.md from the core skills' front matter, so neither can drift from what ships.
// Usage: node scripts/docs/build.mjs [--check]   (--check exits 1 when a committed file is out of date; a test runs it)

import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { COMMANDS } from '../../src/cli/registry.mjs'
import { GLOBAL_OPTIONS } from '../../src/cli/options.mjs'

export const DOC = 'docs/reference/commands.md'
export const SKILLS_DOC = 'docs/reference/skill-catalog.md'
const SKILLS_DIR = fileURLToPath(new URL('../../templates/core/.claude/skills/', import.meta.url))
const GENERIC = { crSkill: 'pr', changeRequest: 'pull or merge request', changeRequests: 'pull or merge requests' }
const generic = (s) => String(s).replace(/\{\{\s*vocab\.(\w+)\s*\}\}/g, (_, k) => GENERIC[k] ?? k)

/** The core skills, from their SKILL.md front matter, in the platform-neutral words. */
export function renderSkills() {
  const rows = readdirSync(SKILLS_DIR).sort().map((dir) => {
    const text = readFileSync(join(SKILLS_DIR, dir, 'SKILL.md'), 'utf8')
    const field = (k) => text.match(new RegExp(`^${k}:\\s*(.+)$`, 'm'))?.[1]?.replace(/^"|"$/g, '') ?? ''
    return `| \`/${generic(field('name'))}\` | ${cell(generic(field('description')))} |`
  })
  return ['# Skill catalog', '', '<!-- Generated by `npm run docs` from templates/core/.claude/skills. Do not edit by hand. -->', '', 'The core skills agent-os installs in every project. On GitLab, `/pr` is installed as `/mr`, with `/pr` kept as an alias. The registry and vendored skills are in [skills.md](skills.md).', '', '| Skill | What it does, and when it is used |', '|---|---|', ...rows, ''].join('\n')
}

const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ')
const flag = (name, o) => `\`--${name}${o.type === 'string' ? ' <value>' : ''}\`${o.short ? ` (\`-${o.short}\`)` : ''}${o.multiple ? ', repeatable' : ''}`

/** The whole reference, one section per command in registry order. */
export async function renderCommands() {
  const out = [
    '# Commands',
    '',
    '<!-- Generated by `npm run docs` from src/cli/registry.mjs and each command module. Do not edit by hand. -->',
    '',
    'Every command prints text, or one JSON object with `--json`. Exit codes: 0 ok, 1 a check failed, 2 the command could not run. Commands that change something take `--dry-run`.',
    '',
    '## Global options',
    '',
    '| Option | What |',
    '|---|---|',
    ...Object.entries(GLOBAL_OPTIONS).map(([n, o]) => `| ${flag(n, o)} | ${cell(o.description)} |`),
    '',
    '## Index',
    '',
    '| Command | Status | What |',
    '|---|---|---|',
    ...COMMANDS.map((c) => `| [\`${c.name}\`](#${c.name}) | ${c.status} | ${cell(c.summary)} |`),
  ]
  for (const c of COMMANDS) {
    out.push('', `## ${c.name}`, '', `${c.summary}. Status: ${c.status}${c.issue ? ` (#${c.issue})` : ''}.`)
    if (!c.load) { out.push('', 'Planned: not implemented yet.'); continue }
    const m = await c.load()
    if (m.usage) out.push('', '```', ...String(m.usage).split('\n'), '```')
    const opts = Object.entries(m.options ?? {})
    if (opts.length) out.push('', '| Option | What |', '|---|---|', ...opts.map(([n, o]) => `| ${flag(n, o)} | ${cell(o.description)} |`))
  }
  return `${out.join('\n')}\n`
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const files = { [DOC]: await renderCommands(), [SKILLS_DOC]: renderSkills() }
  let stale = false
  for (const [file, text] of Object.entries(files)) {
    if (!process.argv.includes('--check')) { writeFileSync(file, text); continue }
    let current = ''
    try { current = readFileSync(file, 'utf8') } catch { /* missing counts as out of date */ }
    if (current !== text) { console.error(`${file} is out of date: run npm run docs`); stale = true }
  }
  if (stale) process.exit(1)
}
